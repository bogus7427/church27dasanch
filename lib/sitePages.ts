export const pageHref = (p: SubPage) => p.href ?? `/info/${p.slug}`;

export function findPage(slug: string) {
  for (const s of SECTIONS) {
    const p = s.pages.find((x) => x.slug === slug);
    if (p) return { section: s, page: p };
  }
  return null;
}
